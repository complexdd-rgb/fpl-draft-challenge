import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

function replaceExact(path, before, after, label) {
  const source = fs.readFileSync(path, 'utf8');
  if (!source.includes(before)) throw new Error(`${label}: expected text not found in ${path}`);
  fs.writeFileSync(path, source.replace(before, after));
}

function replaceAllExpected(path, before, after, expectedCount, label) {
  const source = fs.readFileSync(path, 'utf8');
  const count = source.split(before).length - 1;
  if (count !== expectedCount) throw new Error(`${label}: expected ${expectedCount} matches in ${path}, found ${count}`);
  fs.writeFileSync(path, source.split(before).join(after));
}

