import fs from 'node:fs';

const read = path => fs.readFileSync(path, 'utf8');
const write = (path, value) => fs.writeFileSync(path, value);
const config = JSON.parse(read('config/asset-manifest.json'));
const assets = config.assets || {};

const sourceAssets = JSON.stringify(assets, null, 2).replace(/^/gm, '  ');
const runtime = `/* GENERATED by scripts/build-asset-manifest-runtime.mjs from config/asset-manifest.json.\n   Do not edit version strings here; change the central manifest and rebuild instead. */\n(() => {\n  \"use strict\";\n\n  const source = ${sourceAssets.trimStart()};\n  const assets = Object.freeze(Object.fromEntries(\n    Object.entries(source).map(([key, value]) => [key, Object.freeze({ ...value })])\n  ));\n\n  const get = key => assets[key] || null;\n  const url = key => {\n    const asset = get(key);\n    if (!asset) throw new Error(\`Unknown FPL asset key: \${key}\`);\n    return asset.version ? \`\${asset.path}?v=\${asset.version}\` : asset.path;\n  };\n\n  window.FPL_ASSET_MANIFEST = Object.freeze({\n    version: ${JSON.stringify(config.manifestVersion)},\n    assets,\n    get,\n    url\n  });\n})();\n`;

write('js/asset-manifest.js', runtime);

const assetManifest = assets.assetManifestRuntime;
if (!assetManifest?.path || !assetManifest?.version) throw new Error('assetManifestRuntime must have a path and cache version.');
const tag = `${assetManifest.path}?v=${assetManifest.version}`;
const htmlPath = 'admin.html';
const before = read(htmlPath);
const pattern = /js\/asset-manifest\.js(?:\?v=[^\"']+)?/g;
const matches = before.match(pattern) || [];
if (matches.length !== 1) throw new Error(`Expected exactly one asset-manifest script in admin.html, found ${matches.length}.`);
write(htmlPath, before.replace(pattern, tag));

console.log(`Generated js/asset-manifest.js and pinned admin.html to ${tag}.`);
