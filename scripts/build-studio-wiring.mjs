import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const pathUrl = path => new URL(path, root);
const read = path => fs.readFileSync(pathUrl(path), 'utf8');
const write = (path, before, after) => {
  if (before === after) return false;
  fs.writeFileSync(pathUrl(path), after);
  console.log(`Updated ${path}`);
  return true;
};
const replaceOnce = (source, from, to, label) => {
  if (source.includes(to)) return source;
  const count = source.split(from).length - 1;
  if (count !== 1) throw new Error(`${label}: expected one source marker, found ${count}.`);
  return source.replace(from, to);
};

const manifestConfig = JSON.parse(read('config/asset-manifest.json'));
const assets = manifestConfig.assets || {};
const entry = key => {
  const value = assets[key];
  if (!value?.path) throw new Error(`Asset manifest is missing ${key}.`);
  return value;
};
const assetUrl = key => {
  const value = entry(key);
  return value.version ? `${value.path}?v=${value.version}` : value.path;
};

function renderRuntimeManifest() {
  const sourceAssets = JSON.stringify(assets, null, 2).replace(/^/gm, '  ');
  return `/* GENERATED by scripts/build-studio-wiring.mjs from config/asset-manifest.json.\n   Do not edit version strings here; change the central manifest and rebuild instead. */\n(() => {\n  \"use strict\";\n\n  const source = ${sourceAssets.trimStart()};\n  const assets = Object.freeze(Object.fromEntries(\n    Object.entries(source).map(([key, value]) => [key, Object.freeze({ ...value })])\n  ));\n\n  const get = key => assets[key] || null;\n  const url = key => {\n    const asset = get(key);\n    if (!asset) throw new Error(\`Unknown FPL asset key: \${key}\`);\n    return asset.version ? \`\${asset.path}?v=\${asset.version}\` : asset.path;\n  };\n\n  window.FPL_ASSET_MANIFEST = Object.freeze({\n    version: ${JSON.stringify(manifestConfig.manifestVersion)},\n    assets,\n    get,\n    url\n  });\n})();\n`;
}

{
  const path = 'js/asset-manifest.js';
  const before = fs.existsSync(pathUrl(path)) ? read(path) : '';
  write(path, before, renderRuntimeManifest());
}

{
  const path = 'admin.html';
  const before = read(path);
  let after = before;
  const tag = `  <script src="${assetUrl('assetManifestRuntime')}"></script>`;
  const existing = /  <script src="js\/asset-manifest\.js(?:\?v=[^"]+)?"><\/script>/;
  if (existing.test(after)) after = after.replace(existing, tag);
  else {
    const marker = '  <title>FPL Challenge Studio</title>\n';
    if (!after.includes(marker)) throw new Error('admin.html title marker was not found.');
    after = after.replace(marker, `${marker}${tag}\n`);
  }
  write(path, before, after);
}

