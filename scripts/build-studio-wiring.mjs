{
  const path = 'js/leaderboard-config.js';
  const before = read(path);
  let after = before;
  const marker = '// Non-critical environment features live in named loaders instead of this configuration file.';
  if (!after.includes('// Studio runtime feature ownership lives in studio-bootstrap.js.')) {
    const index = after.indexOf(marker);
    if (index < 0) throw new Error('leaderboard-config feature-loader marker was not found.');
    after = after.slice(0, index) + `// Studio runtime feature ownership lives in studio-bootstrap.js. Live play keeps its\n// own deferred feature loader and does not depend on the Studio asset manifest.\nif (!window.FPL_IS_STUDIO) {\n  const featureLoader = document.createElement(\"script\");\n  featureLoader.src = new URL(\"js/live-feature-loader.js\", document.baseURI).toString();\n  featureLoader.async = true;\n  featureLoader.dataset.fplFeatureLoader = \"live\";\n  document.head.appendChild(featureLoader);\n}\n\nwindow.dispatchEvent(new CustomEvent(\"fpl:leaderboard-config-ready\", {\n  detail: window.FPL_LEADERBOARD_CONFIG\n}));\n`;
  }
  write(path, before, after);
}

for (const path of [
  'js/asset-manifest.js',
  'js/studio-bootstrap.js',
  'js/prompt-studio-loader.js',
  'js/admin-import-tools.js',
  'js/studio-feature-loader.js',
  'js/leaderboard-config.js'
]) {
  execFileSync(process.execPath, ['--check', fileURLToPath(new URL(path, root))], { stdio: 'inherit' });
}

