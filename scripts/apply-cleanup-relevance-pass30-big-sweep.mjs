import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const read = path => fs.readFileSync(path, 'utf8');
const write = (path, content) => fs.writeFileSync(path, content);

function replaceExact(path, before, after, label) {
  const source = read(path);
  const count = source.split(before).length - 1;
  if (count !== 1) throw new Error(`${label}: expected exactly one match in ${path}, found ${count}`);
  write(path, source.replace(before, after));
}

function replaceRegex(path, pattern, after, label) {
  const source = read(path);
  const match = source.match(pattern);
  if (!match) throw new Error(`${label}: expected match not found in ${path}`);
  const next = source.replace(pattern, after);
  if (next === source) throw new Error(`${label}: replacement did not change ${path}`);
  write(path, next);
}

